/**
 * Banderas via flag-icons (CSS + SVG) — compatibles con Windows/PC.
 * Requiere: flag-icons CSS en la pagina (clase .fi .fi-xx)
 */
function isoToFlagClass(iso) {
    if (!iso || iso.length !== 2) return 'fi fi-xx';
    return 'fi fi-' + iso.toLowerCase();
}

/** @deprecated Usar isoToFlagClass — los emoji de bandera no se ven en Windows */
function isoToFlag(iso) {
    return isoToFlagClass(iso);
}

